let assertions = 0;
function page(saved, options = {}) {
  const errors = [], downloads = [];
  const virtualConsole = new VirtualConsole();
  virtualConsole.on('jsdomError', error => errors.push(error));
  const dom = new JSDOM(html, {url: 'https://quiz.example/super-quiz/', runScripts: 'outside-only', pretendToBeVisual: true, virtualConsole});
  const w = dom.window, d = w.document;
  let clock = 1000;
  Object.defineProperty(w.performance, 'now', {value: () => clock});
  w.HTMLElement.prototype.scrollIntoView = function () {};
  if (!w.HTMLDialogElement.prototype.showModal) w.HTMLDialogElement.prototype.showModal = function () {this.open = true;};
  if (!w.HTMLDialogElement.prototype.close) w.HTMLDialogElement.prototype.close = function () {this.open = false;};
  w.URL.createObjectURL = blob => {downloads.push(blob); return 'blob:quiz-result';};
  w.URL.revokeObjectURL = () => {};
  const click = w.HTMLAnchorElement.prototype.click;
  w.HTMLAnchorElement.prototype.click = function () {if (!this.download) click.call(this);};
  if (saved !== undefined) w.localStorage.setItem(key, typeof saved === 'string' ? saved : JSON.stringify(saved));
  if (options.old) w.localStorage.setItem('sprott-super-quiz-v1', '{}');
  if (options.storageFailure) w.Storage.prototype.setItem = () => {throw new Error('Quota exceeded');};
  for (const file of ['data.js', 'bank-1.js', 'bank-2.js', 'bank-3.js', 'bank-4.js', 'levels.js', 'engine.js', 'written-data.js', 'written-engine.js', 'write-in.js', 'app.js']) w.eval(fs.readFileSync('super-quiz/' + file, 'utf8'));
  const get = selector => {const element = d.querySelector(selector); assert(element, selector); return element;};
  const press = (selector, detail = 1, elapsed = 250) => {clock += elapsed; const el = get(selector); el.dispatchEvent(new w.MouseEvent('click', {bubbles: true, cancelable: true, detail}));};
  const action = (name, detail = 1, elapsed = 250) => press('[data-action="' + name + '"]', detail, elapsed);
  const submit = id => get('#' + id).dispatchEvent(new w.Event('submit', {bubbles: true, cancelable: true}));
  const read = () => JSON.parse(w.localStorage.getItem(key));
  const select = values => {
    for (const input of d.querySelectorAll('input[name="answer"]')) input.checked = values.includes(Number(input.value));
    get('input[name="answer"]').dispatchEvent(new w.Event('change', {bubbles: true}));
  };
  const close = () => {assert.deepEqual(errors, [], errors.map(e => e.message).join('\n')); assertions++; w.close();};
  return {w, d, get, press, action, submit, read, select, close, errors, downloads};
}
